import { readdirSync, mkdirSync, copyFileSync } from 'node:fs';
import { resolve, join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'release-assets');
mkdirSync(out, { recursive: true });
const windows = process.platform === 'win32';
if (!windows && process.platform !== 'linux') throw new Error('Unsupported release platform');
const bundle = join(root, 'target/release/bundle', windows ? 'nsis' : 'appimage');
const matches = readdirSync(bundle).filter(name => name.endsWith(windows ? '.exe' : '.AppImage'));
if (matches.length !== 1) throw new Error(`Expected exactly one release package, found ${matches.length}`);
copyFileSync(join(bundle, matches[0]), join(out, windows ? 'Meraki-Setup.exe' : 'Meraki.AppImage'));
